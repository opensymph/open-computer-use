// keyvalForName mirrors runtime.py's keyval(): Gdk.keyval_from_name first
// (the static X11 keysym table below), then the single-character ord()
// fallback, then the pinned "Unsupported key: <name>" error.
func keyvalForName(name string) (uint32, error) {
	if value, ok := x11KeysymValues[name]; ok && value != 0 {
		return value, nil
	}
	if runes := []rune(name); len(runes) == 1 {
		return uint32(runes[0]), nil
	}
	return 0, fmt.Errorf("Unsupported key: %s", name)
}

